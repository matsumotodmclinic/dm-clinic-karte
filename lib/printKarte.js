// ── ① フッターの空行（紙は 1 行・電子カルテは 3 行） ─────────────────
//
// 同じカルテ本文でも、要る隙間が違う:
//   電子カルテに貼るとき → フッター（山）の上は **3 行**空けたい（院長が追記する場所）
//   紙に印刷するとき     → その 3 行は**ただの無駄**（実際に目標HbA1c 以下が裏のページに送られた）
//
// ⇒ **正本は電子カルテ側（3 行）**にして、紙に出すときだけここで 1 行に詰める。
//   逆（紙を正本にしてコピー時に増やす）にすると、スタッフが画面からコピーしたものと
//   アプリが貼り付けるものが食い違うので採らない。
//
// カルテ本文はフッター以外で空行が連続しない（`prompt.test.mjs` の空行ルールで検査している）。
// なのでこの置換が効くのはフッターの記入欄だけ。
export function collapseBlankLinesForPrint(text) {
  return String(text || '').replace(/\n{3,}/g, '\n\n')
}

// ── ② 西暦 → 和暦（ドクターキューブの貼り付け用） ───────────────────
//
// 院長 2026-10-15「貼り付けしA4出力する際に自動で、和暦に換算するようなシステムにしてほしい」。
// ドクターキューブの事前WEB問診は測定年月が**西暦**（例「検査した年月： 2026年10月」）。
// 当院のカルテは**和暦のみ**（CLAUDE.md の和暦統一ルール）なので、紙の上で表記が混ざる。
//
// ★変換するのは**紙に出すときだけ**。保存してある貼り付け原文（form_data.drQube.text）は
//   患者が入力したままにしておく（後から原文を確かめられるように）。
//
// 元号の切り替わりは「日」まで見ないと決まらないが、問診に出るのは年月がほとんどなので
// **月で判定**する（令和=2019年5月〜 / 平成=1989年1月〜2019年4月 / 昭和=1926年〜1988年）。
// 1989年1月は昭和64年(1/1-1/7)と平成元年が混在するが、検査年月の実用上は平成とする。
// from = 元号が始まった「年*12+月」。base = 元年にあたる西暦。
// ★base は from から割り出さないこと。昭和は 12 月始まりなので、割り算すると 1 年ずれる
//   （実測: 1988年12月 が S62.12 になった。正しくは S63.12）。
const ERAS = [
  { code: 'R', name: '令和', from: 2019 * 12 + 5, base: 2019 },
  { code: 'H', name: '平成', from: 1989 * 12 + 1, base: 1989 },
  { code: 'S', name: '昭和', from: 1926 * 12 + 12, base: 1926 },
]

/** 西暦の年月（1 始まりの月）を `R8.10` の形にする。範囲外なら null */
export function toWareki(year, month) {
  const y = Number(year)
  const m = Number(month)
  if (!Number.isInteger(y) || !Number.isInteger(m) || m < 1 || m > 12) return null
  if (y < 1926 || y > 2100) return null   // 明らかに年でないものは触らない
  const key = y * 12 + m
  const era = ERAS.find(e => key >= e.from)
  if (!era) return null
  return { code: era.code, name: era.name, year: y - era.base + 1, month: m }
}

// 「2026年10月」「2026年10月15日」と「2026/10」「2026/10/15」「2026-10-15」の 2 形を拾う。
// 年だけ（「2026年」）は、元号の切り替わり月を決められないので触らない。
//
// ★空白に \s を使わないこと。改行をまたいで次の行の数字を日として食い、**行が 1 行に潰れる**
//   （実測: 「1989年1月␊2026/10/15 受診」→「H1.1.2026/10/15 受診」）。
// ★「○年○月」の後ろの数字を日と見なさない。「2026年10月 3回」が R8.10.3 になる
//   （日は「日」が付いているときだけ）。
const WA = {
  ymd: /(\d{4})[ 　]*年[ 　]*(\d{1,2})[ 　]*月(?:[ 　]*(\d{1,2})[ 　]*日)?/g,
  slash: /(?<!\d)(\d{4})[/\-.](\d{1,2})(?:[/\-.](\d{1,2}))?(?!\d)/g,
}

/**
 * 文中の西暦の年月（日）を和暦に置き換える。例: 「2026年10月」→「R8.10」
 * 変換できない並びはそのまま残す（勝手に消さない）。
 */
export function toWarekiForPrint(text) {
  const sub = (all, y, m, d) => {
    const w = toWareki(y, m)
    if (!w) return all
    return d ? `${w.code}${w.year}.${w.month}.${Number(d)}` : `${w.code}${w.year}.${w.month}`
  }
  return String(text || '').replace(WA.ymd, sub).replace(WA.slash, sub)
}
